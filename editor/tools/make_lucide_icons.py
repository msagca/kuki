# Writes `include/icons_lucide.hpp` from the `codepoints.json` that ships with a Lucide release, so
# that the names the editor writes icons by are the names of the glyphs in the font it loads.
#
#   python make_lucide_icons.py <lucide-static>/font/codepoints.json <version> ../include/icons_lucide.hpp
#
# Run again whenever `asset/font/lucide.ttf` is replaced, from the same release as the font. The
# two have to come from one release: Lucide gives a new icon the next free codepoint, and has moved
# existing ones between releases, so a header from one and a font from another draws the wrong
# picture with nothing to say so. That is also why this header is generated here and not taken from
# a collection of icon headers kept up by somebody else on a schedule of their own.
import json
import sys


def main() -> None:
    if len(sys.argv) != 4:
        raise SystemExit("usage: make_lucide_icons.py <codepoints.json> <version> <output header>")
    source, version, output = sys.argv[1:]
    with open(source, encoding="utf-8") as f:
        codepoints = json.load(f)
    lines = [
        "#pragma once",
        f"// Generated by tools/make_lucide_icons.py from Lucide {version}. Do not edit: regenerate it with",
        "// the font. Each is the icon's glyph as a UTF-8 string, to be written into a label beside its text",
        '// -- `ICON_LC_PLAY " Play"`.',
        "// NOLINTBEGIN",
        f"#define ICON_LC_MIN 0x{min(codepoints.values()):04x}",
        f"#define ICON_LC_MAX 0x{max(codepoints.values()):04x}",
    ]
    for name, code in sorted(codepoints.items()):
        macro = "ICON_LC_" + name.upper().replace("-", "_")
        text = "".join(f"\\x{byte:02x}" for byte in chr(code).encode("utf-8"))
        lines.append(f'#define {macro} "{text}"')
    lines.append("// NOLINTEND")
    with open(output, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Wrote {len(codepoints)} icons to {output}")


main()
